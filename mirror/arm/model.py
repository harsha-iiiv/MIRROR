"""MuJoCo model of a kit-packing scene with an articulated arm.

The scene geometry (table, trays, walls, objects, beads) is generated by the
same functions as the legacy gripper backend (:mod:`mirror.sim.model`), so the
two backends differ only in the robot.

Robot. A Universal Robots UR5e or UR10e (six revolute joints; kinematics,
inertias, joint ranges and collision capsules from the vendored models in
``mirror/assets/universal_robots_*``) carries the MIRROR parallel-jaw
gripper (same palm, finger and pad geometry as the legacy backend, from
:mod:`mirror.geometry`) on its tool flange. The gripper body's origin is the
tool centre point (TCP), so planner waypoints are TCP poses for both backends.

The arm is ceiling-mounted above the table (see :class:`Mount`), so its links
can reach both sides of a wall over the top of it while the carried object and
the gripper still have to follow the planner's route.

Actuation. Each arm joint has a position servo (PD) with force limits taken
from the vendored model. The executor adds velocity feed-forward through the
position command. Gravity on the arm and gripper links is compensated through
the actuators (MuJoCo ``gravcomp`` routed by ``actuatorgravcomp``, so it counts
against the force limits); the payload is not compensated. This stands in for
the model-based gravity compensation of an industrial controller. The fingers
use the legacy jaw actuators unchanged.

The arm geoms are drawn with their collision shapes: there are no visual
meshes in this repository.
"""
from __future__ import annotations

import math
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path

import mujoco
import numpy as np

from mirror.contracts import SceneState
from mirror.geometry import GRIPPER
from mirror.sim import model as gm
from mirror.sim.model import (FINGER_ARMATURE, FINGER_FORCE, FINGER_JOINTS, FINGER_KP, FINGER_RANGE,
                              FRICTION_OBJECT, FRICTION_PAD, FRICTION_STATIC, GROUP_ROBOT, TIMESTEP,
                              SceneIndex, _box, _f)

ASSETS = Path(__file__).resolve().parents[1] / "assets"
MENAGERIE_COMMIT = "98a70c569c4c1b6da467a20012f766ee1f8dc521"

ARM_JOINTS = ("shoulder_pan_joint", "shoulder_lift_joint", "elbow_joint",
              "wrist_1_joint", "wrist_2_joint", "wrist_3_joint")
ARM_LINKS = ("base", "shoulder_link", "upper_arm_link", "forearm_link",
             "wrist_1_link", "wrist_2_link", "wrist_3_link")
PREFIX = "arm/"

ARM_DAMPRATIO = 1.0


@dataclass(frozen=True)
class ArmSpec:
    """A vendored arm model and the servo settings used with it.

    ``kp``: position-servo gains (N m / rad), chosen here. ``force``: actuator
    force limits (N m) from the vendored model. ``speed``: joint speed limits
    (rad/s) used by the executor's time scaling, from the manufacturer's rated
    joint speeds."""

    key: str
    name: str
    xml: Path
    default_class: str
    kp: tuple
    force: tuple
    speed: tuple

    @property
    def source(self) -> str:
        return (f"MuJoCo Menagerie universal_robots_{self.key} (commit {MENAGERIE_COMMIT}), BSD-3-Clause, "
                "Copyright 2018 ROS Industrial Consortium; visual meshes removed")


_D = math.radians
UR5E = ArmSpec("ur5e", "UR5e", ASSETS / "universal_robots_ur5e" / "ur5e.xml", "ur5e",
               kp=(4000.0, 4000.0, 3000.0, 600.0, 600.0, 400.0),
               force=(150.0, 150.0, 150.0, 28.0, 28.0, 28.0),
               speed=(_D(180),) * 6)
UR10E = ArmSpec("ur10e", "UR10e", ASSETS / "universal_robots_ur10e" / "ur10e.xml", "ur10e",
                kp=(8000.0, 8000.0, 4000.0, 1000.0, 1000.0, 600.0),
                force=(330.0, 330.0, 150.0, 56.0, 56.0, 56.0),
                speed=(_D(120), _D(120), _D(180), _D(180), _D(180), _D(180)))
ARMS = {a.key: a for a in (UR5E, UR10E)}

# Distance from the flange face to the TCP along the tool axis: the gripper
# palm's top face sits on the flange.
FLANGE_TO_TCP = GRIPPER.palm_center_z + GRIPPER.palm_half[2]


@dataclass(frozen=True)
class Mount:
    """Which arm, and the pose of its base in the world. The default hangs the
    arm from a ceiling plate (base +z pointing down)."""

    arm: str = "ur5e"
    pos: tuple = (0.0, 0.0, 0.95)
    quat: tuple = (0.0, 1.0, 0.0, 0.0)   # 180 deg about world x
    name: str = "ceiling_centre"
    tool_extension: float = 0.0          # m of straight tool tube between the flange and the gripper palm

    @property
    def spec(self) -> ArmSpec:
        return ARMS[self.arm]


# UR10e hanging from a ceiling plate 0.95 m above the table, 0.62 m beyond the
# table centre in +y (just past the table edge), with a 0.30 m tool tube. The
# offset keeps the workspace out of the shoulder-singular column under the
# base; the tube keeps the wrist above the wall tops during carries.
DEFAULT_MOUNT = Mount(arm="ur10e", pos=(0.0, 0.62, 0.95), name="ceiling_y+0.62_ur10e", tool_extension=0.30)


@dataclass
class ArmIndex(SceneIndex):
    """SceneIndex for the arm model. ``robot_*`` fields refer to the arm joints."""

    arm_qposadr: list[int] = field(default_factory=list)
    arm_dofadr: list[int] = field(default_factory=list)
    arm_actuators: list[int] = field(default_factory=list)
    arm_joint_ids: list[int] = field(default_factory=list)
    arm_range: np.ndarray | None = None          # (6, 2)
    arm_geoms: list[int] = field(default_factory=list)
    arm_bodies: list[int] = field(default_factory=list)
    gripper_geoms: list[int] = field(default_factory=list)
    mount: Mount = DEFAULT_MOUNT


@lru_cache(maxsize=4)
def _arm_tree(arm: str) -> tuple[str, str]:
    """(default-class xml, base body xml) from the vendored model, with every
    body, joint and geom name prefixed and the collision geoms named."""
    root = ET.parse(ARMS[arm].xml).getroot()
    default = root.find("default").find("default")          # class "ur5e"
    base = root.find("worldbody").find("body")
    for b in base.iter("body"):
        b.set("name", PREFIX + b.get("name"))
        b.set("gravcomp", "1")
        n = 0
        for g in list(b.findall("geom")):
            if g.get("mesh"):
                b.remove(g)
                continue
            g.set("name", f"{b.get('name')}/c{n}")
            g.set("group", str(GROUP_ROBOT))
            g.set("rgba", "0.42 0.62 0.78 1" if n % 2 == 0 else "0.78 0.79 0.80 1")
            n += 1
        for j in b.findall("joint"):
            j.set("name", PREFIX + j.get("name"))
            j.set("actuatorgravcomp", "true")
        for s in b.findall("site"):
            s.set("name", PREFIX + s.get("name"))
    return ET.tostring(default, encoding="unicode"), ET.tostring(base, encoding="unicode")


TOOL_TUBE_RADIUS = 0.020   # inside the palm's footprint (palm half extents 0.025 x 0.055 m)
TOOL_TUBE_MASS_PER_M = 0.6  # kg/m (aluminium tube)


def _gripper_xml(extension: float = 0.0) -> str:
    """The legacy gripper (palm, TCP site, two fingers), mounted on the flange
    through an optional straight tool tube: origin at the TCP, local -z
    (approach) along the flange normal."""
    ph, fh = GRIPPER.palm_half, GRIPPER.finger_half
    pad = (0.25, 0.25, 0.28, 1)
    palm = (0.18, 0.18, 0.20, 1)
    # wrist_3_link frame: the flange normal is +y, the flange face at y = 0.1.
    pos = (0.0, 0.1 + FLANGE_TO_TCP + extension, 0.0)
    quat = (math.sqrt(0.5), math.sqrt(0.5), 0.0, 0.0)   # 90 deg about x: gripper -z = +y
    tube = ""
    if extension > 0:
        top = FLANGE_TO_TCP
        tube = (f'<geom name="gripper/tool_tube" type="cylinder" size="{TOOL_TUBE_RADIUS:g} {extension / 2:.6g}" '
                f'pos="0 0 {top + extension / 2:.6g}" rgba="0.55 0.56 0.58 1" group="{GROUP_ROBOT}" '
                f'friction="{_f(FRICTION_OBJECT)}" mass="{TOOL_TUBE_MASS_PER_M * extension:.6g}"/>')
    return f"""
<body name="gripper" pos="{_f(pos)}" quat="{_f(quat)}" gravcomp="1">
  {tube}
  {_box("gripper/palm", (0, 0, GRIPPER.palm_center_z), ph, palm, GROUP_ROBOT, FRICTION_OBJECT, mass=0.25)}
  <site name="tcp" pos="0 0 0" size="0.004" rgba="1 0 0 0.6" group="{GROUP_ROBOT}"/>
  <body name="gripper_finger_l" gravcomp="1">
    <joint name="gripper_finger_l" type="slide" axis="0 1 0" range="{_f(FINGER_RANGE)}" limited="true" damping="1" armature="{FINGER_ARMATURE}" actuatorgravcomp="true"/>
    {_box("gripper/finger_l", (0, fh[1], GRIPPER.finger_center_z), fh, pad, GROUP_ROBOT, FRICTION_PAD, mass=0.03, condim=4)}
  </body>
  <body name="gripper_finger_r" gravcomp="1">
    <joint name="gripper_finger_r" type="slide" axis="0 -1 0" range="{_f(FINGER_RANGE)}" limited="true" damping="1" armature="{FINGER_ARMATURE}" actuatorgravcomp="true"/>
    {_box("gripper/finger_r", (0, -fh[1], GRIPPER.finger_center_z), fh, pad, GROUP_ROBOT, FRICTION_PAD, mass=0.03, condim=4)}
  </body>
</body>"""


def _robot_xml(mount: Mount) -> str:
    _, base = _arm_tree(mount.arm)
    # Insert the gripper into wrist_3_link (the flange link).
    marker = f'name="{PREFIX}wrist_3_link"'
    i = base.index(marker)
    j = base.index("</body>", i)
    base = base[:j] + _gripper_xml(mount.tool_extension) + base[j:]
    plate = _box("arm/mount_plate", (0, 0, -0.01), (0.08, 0.08, 0.01), (0.30, 0.30, 0.32, 1),
                 gm.GROUP_STATIC, FRICTION_STATIC, contype=0, conaffinity=0)
    return (f'<body name="arm/mount" pos="{_f(mount.pos)}" quat="{_f(mount.quat)}">'
            f"{plate}{base}</body>")


def _actuators_xml(arm: ArmSpec) -> str:
    rows = []
    for j, kp, frc in zip(ARM_JOINTS, arm.kp, arm.force):
        rows.append(f'<position name="{PREFIX}{j}" joint="{PREFIX}{j}" kp="{kp:g}" dampratio="{ARM_DAMPRATIO:g}" '
                    f'ctrlrange="-6.2832 6.2832" ctrllimited="true" forcerange="{-frc:g} {frc:g}" forcelimited="true"/>')
    for j in FINGER_JOINTS:
        rows.append(f'<position name="{j}" joint="{j}" kp="{FINGER_KP}" dampratio="1" '
                    f'ctrlrange="{_f(FINGER_RANGE)}" ctrllimited="true" forcerange="{-FINGER_FORCE} {FINGER_FORCE}" forcelimited="true"/>')
    return "<actuator>" + "".join(rows) + "</actuator>"


def arm_scene_xml(scene: SceneState, mount: Mount = DEFAULT_MOUNT) -> str:
    """MJCF of ``scene`` with the arm in place of the free-flying gripper."""
    default, _ = _arm_tree(mount.arm)
    xml = gm.scene_xml(scene)
    # Replace the legacy robot body and its actuators.
    start = xml.index('<body name="gripper_carriage"')
    # the carriage body is the outermost; find its matching close tag
    depth, k = 0, start
    while True:
        o = xml.find("<body", k)
        c = xml.find("</body>", k)
        if o != -1 and o < c:
            depth += 1
            k = o + 5
        else:
            depth -= 1
            k = c + 7
            if depth == 0:
                break
    xml = xml[:start] + _robot_xml(mount) + xml[k:]
    a0, a1 = xml.index("<actuator>"), xml.index("</actuator>") + len("</actuator>")
    xml = xml[:a0] + _actuators_xml(mount.spec) + xml[a1:]
    xml = xml.replace('<compiler angle="radian" autolimits="true"/>',
                      '<compiler angle="radian" autolimits="true"/>\n  <default>' + default + "</default>")
    return xml.replace(f'<mujoco model="mirror_{scene.scene_id}">', f'<mujoco model="mirror_arm_{scene.scene_id}">')


def _label_for_geom(name: str, scene: SceneState) -> tuple[str, str]:
    if name.startswith(PREFIX) and not name.startswith("arm/mount"):
        return "arm", "arm"
    if name.startswith("arm/mount"):
        return "arm_mount", "arm_mount"
    return gm._label_for_geom(name, scene)


def build_arm_model(scene: SceneState, mount: Mount = DEFAULT_MOUNT) -> tuple[mujoco.MjModel, ArmIndex]:
    ids = [o.id for o in scene.objects]
    if len(set(ids)) != len(ids):
        raise ValueError("object ids must be unique")
    model = mujoco.MjModel.from_xml_string(arm_scene_xml(scene, mount))
    if abs(model.opt.timestep - TIMESTEP) > 1e-12:  # pragma: no cover
        raise AssertionError("timestep differs from the legacy backend")

    def _id(kind, n):
        i = mujoco.mj_name2id(model, kind, n)
        if i < 0:
            raise KeyError(n)
        return i

    bid = lambda n: _id(mujoco.mjtObj.mjOBJ_BODY, n)
    jid = lambda n: _id(mujoco.mjtObj.mjOBJ_JOINT, n)
    aid = lambda n: _id(mujoco.mjtObj.mjOBJ_ACTUATOR, n)
    gid = lambda n: _id(mujoco.mjtObj.mjOBJ_GEOM, n)
    labels, owners = [], []
    for g in range(model.ngeom):
        lab, own = _label_for_geom(model.geom(g).name, scene)
        labels.append(lab)
        owners.append(own)
    codes: dict[str, int] = {}
    for lab in labels:
        codes.setdefault(lab, len(codes))
    bead_bodies, bead_q = {}, {}
    for o in scene.objects:
        if o.kind == "cup":
            bead_bodies[o.id] = [bid(f"{o.id}/bead{i}") for i in range(o.beads)]
            bead_q[o.id] = [int(model.jnt_qposadr[jid(f"{o.id}/bead{i}/free")]) for i in range(o.beads)]
    body_names = [model.body(b).name for b in range(model.nbody)]
    static_bodies = [b for b in range(1, model.nbody) if model.body_weldid[b] == 0]
    dynamic_bodies = [b for b in range(1, model.nbody) if model.body_weldid[b] != 0]
    arm_j = [jid(PREFIX + j) for j in ARM_JOINTS]
    arm_bodies = [bid(PREFIX + b) for b in ARM_LINKS]
    idx = ArmIndex(
        object_ids=ids,
        object_kinds={o.id: o.kind for o in scene.objects},
        object_body={o.id: bid(o.id) for o in scene.objects},
        object_qposadr={o.id: int(model.jnt_qposadr[jid(f"{o.id}/free")]) for o in scene.objects},
        object_dofadr={o.id: int(model.jnt_dofadr[jid(f"{o.id}/free")]) for o in scene.objects},
        bead_bodies=bead_bodies,
        bead_qposadr=bead_q,
        geom_label=labels,
        geom_owner=owners,
        finger_l_geom=gid("gripper/finger_l"),
        finger_r_geom=gid("gripper/finger_r"),
        gripper_body=bid("gripper"),
        robot_qposadr=[int(model.jnt_qposadr[j]) for j in arm_j],
        robot_dofadr=[int(model.jnt_dofadr[j]) for j in arm_j],
        finger_qposadr=[int(model.jnt_qposadr[jid(j)]) for j in FINGER_JOINTS],
        robot_actuators=[aid(PREFIX + j) for j in ARM_JOINTS],
        finger_actuators=[aid(j) for j in FINGER_JOINTS],
        static_bodies=static_bodies,
        dynamic_bodies=dynamic_bodies,
        body_names=body_names,
        tray_ids=[t.id for t in scene.trays],
        obstacle_ids=[o.id for o in scene.obstacles],
        label_codes=codes,
        geom_label_code=np.array([codes[lab] for lab in labels], dtype=np.int32),
        arm_qposadr=[int(model.jnt_qposadr[j]) for j in arm_j],
        arm_dofadr=[int(model.jnt_dofadr[j]) for j in arm_j],
        arm_actuators=[aid(PREFIX + j) for j in ARM_JOINTS],
        arm_joint_ids=arm_j,
        arm_range=np.array([model.jnt_range[j] for j in arm_j], dtype=float),
        arm_geoms=[g for g in range(model.ngeom) if owners[g] == "arm"],
        arm_bodies=arm_bodies,
        gripper_geoms=[g for g in range(model.ngeom) if owners[g] == "gripper"],
        mount=mount,
    )
    return model, idx
